	/**
	 * Project the point <i>p</i> onto the line spanned by <i>v0</i> and <i>v1</i> perpendicularly.
	 * @param dst
	 * @param p
	 * @param v0
	 * @param v1
	 * @param metric	a metric from P3! (not P5)
	 * @return
	 */
	public static double[] projectPointOntoLine(double[] dst, double[] p, double[] v0, double[] v1, int metric) {
		if (dst == null) dst = new double[4];
		if (metric == Pn.EUCLIDEAN)	{
			double[] dv = Rn.subtract(null, v1, v0);
			double[] dp = Rn.subtract(null, p, v0);
			double[] proj = Rn.projectOnto(null, dp, dv);
			Rn.add(dst, v0, proj);
			return dst;
		}
		double[] polar0 = Pn.polarizePoint(null, v0, metric);
		double[] polar1 = Pn.polarizePoint(dst, v1, metric);
		double[] line = lineFromPlanes(null, polar0, polar1);
		double[] plane = lineJoinPoint(null, line, p);
		P3.lineIntersectPlane(dst, v0, v1, plane);
		return dst;
		}

	public static double[] projectPointOntoLine(double[] dst, double[] p, double[] line, int metric) {
		if (dst == null) dst = new double[4];
		double[] polarLine = polarize(null, line, metric);
		double[] plane = lineJoinPoint(null, polarLine, p);
		lineIntersectPlane(dst, line, plane);
		return dst;
		}

