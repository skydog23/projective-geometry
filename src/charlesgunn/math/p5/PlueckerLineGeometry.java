	/**
	  * Calculate Pluecker coordinates for the line spanned by <i>p0</i> and <i>p1</i>.
	  * These are basically the six 2x2 minors of the 2x4 matrix formed by the two points;
	  * the fifth element has its sign reversed so the inner product has a nice symmetric form
	  * @param dst
	  * @param p0
	  * @param p1
	  * @return
	  */
	 public static double[] lineFromPoints(double[] dst, double[] p0, double[] p1)	{
		if (p0.length != 4 || p1.length != 4) {
			throw new IllegalArgumentException("Input points must be homogeneous vectors");
		}
		double[] coords;
		if (dst == null)	coords = new double[6];
		else 				coords = dst;
		coords[0] = p0[0]*p1[1] - p0[1]*p1[0];
		coords[1] = p0[0]*p1[2] - p0[2]*p1[0];
		coords[2] = p0[0]*p1[3] - p0[3]*p1[0];
		coords[3] = p0[1]*p1[2] - p0[2]*p1[1];
		coords[4] = p0[3]*p1[1] - p0[1]*p1[3];
		coords[5] = p0[2]*p1[3] - p0[3]*p1[2];
		return coords;
	}

	public static double[] lineFromPlanes(double[] dst, double[] plane0, double[] plane1)	{
		 dst = lineFromPoints(dst, plane0, plane1);
		 return dualizeLine(dst, dst);
	 }

	public static double[] intersectionPoint(double[] dst, double[] line0, double[] line1) {
		 if (dst == null) dst = new double[4];
//		 System.err.println("Line0 = "+Rn.toString(line0));
//		 System.err.println("Line1 = "+Rn.toString(line1));
		 double norm = Math.abs(innerProduct(line0, line1));
		if (norm > tolerance) {
			System.err.println("Norm exceeds tolerance: " + norm + " > " + tolerance);
			 throw new IllegalArgumentException("These two lines do not intersect");
		}
		return intersectionPointUnchecked(dst, line0, line1);
	 }
	
	public static double[] intersectionPlane(double[] dst, double[] line0, double[] line1) {
		double[] dline0 = dualizeLine(null, line0);
		double[] dline1 = dualizeLine(null, line1);
		return intersectionPoint(dst, dline0, dline1);
	 }
	
	public static double[] intersectionPointUnchecked(double[] dst, double[] line0, double[] line1) {
		 if (dst == null) dst = new double[4];
//		 System.err.println("Line0 = "+Rn.toString(line0));
//		 System.err.println("Line1 = "+Rn.toString(line1));
		 double[] mm = Rn.times(null,
				 lineToSkewMatrix(null, dualizeLine(null, line0)),
				 lineToSkewMatrix(null, line1));
		 // every column of mm should be the same point, the intersection point of the two lines
		 Matrix m = new Matrix(mm);
		 int i;
		 double norm1 = Rn.maxNorm(line0),
		 	norm2 = Rn.maxNorm(line1);
		 if (norm2 > norm1) norm1 = norm2;
		 int bestColumn = -1, biggestEntry = -1;
		 // reject columns which are the null vector (occurs when line lies in that coordinate plane)
		 // we require an entry greater than tolerance
		 double maxval = tolerance*norm1;
		 // first find a nonzero column, and its biggest entry
		 for (i = 0; i<4; ++i)	{
			 for (int j = 0; j<4; ++j) {
				 double absv = Math.abs(mm[i+4*j]);
				 if (absv > maxval) {
					 maxval = absv;
					 bestColumn = i;
					 biggestEntry = j;
				 }
			 }
			 if (bestColumn != -1) break;
			 //if (Rn.euclideanNormSquared(m.getColumn(i)) > norm*10E-16) break;
		 }
		 if (bestColumn == -1) throw new IllegalStateException("lines are same");
		 // compare the biggest entries of the remaining columns to find the best column to use
		 for (i = bestColumn+1; i<4; ++i)	{
			 double d = Math.abs(mm[i+4*biggestEntry]);
			 if (d > maxval) {maxval = d; bestColumn = i;}
		 }
		 dst[0] = mm[bestColumn+0];
		 dst[1] = mm[bestColumn+4];
		 dst[2] = mm[bestColumn+8];
		 dst[3] = mm[bestColumn+12];
		 return dst;
	 }

	/**
	 * Pluecker line coordinates can be arranged in a 4x4 skew symmetric matrix <i>M</i> such
	 * that <i>M</i> is the polarizing operator: if the original line was produced by two points,
	 * then it acts on points to give the plane spanned
	 * by the point and the line; if it was generated by two planes, then it acts on planes to give
	 * the intersection point of the line and the plane.
	 * If it's not a line, then it acts on points to give the null plane of the point, and so on.
	 * Warning: this and the following method act on points (planes) of the form (w,x,y,z), not (x,y,z,w)!
	 * @param m
	 * @param pl
	 * @return
	 */
	 public static double[] lineToSkewMatrix(double[] m, double[] pl) {
		if (m == null) m = new double[16];
		m[0] = m[5] = m[10] = m[15] = 0.0;
		m[4] = -(m[1] = pl[5]);
		m[8] = -(m[2] = pl[4]);
		m[12] = -(m[3] = pl[3]);
		m[9] = -(m[6] = pl[2]);
		m[13] = -(m[7] = -pl[1]);		// here's the strange minus sign! (p42 instead of p24 in formulas)
		m[14] = -(m[11] = pl[0]);
		return m;
		
	}

	/**
	 * Pluecker coordinates for the same line are different depending on
	 * whether the line is considered as the join of two points or the cut of two planes.
	 * This method converts between the two coordinate systems.
	 * @param dst
	 * @param src
	 * @return
	 */
	 public static double[] dualizeLine(double[] dst, double[] src) {
		if (dst == null) dst = new double[6];
		double[] tmp = null;
		if (dst == src)  tmp = new double[6];
		else tmp = dst;
		for (int i = 0; i<6; ++i) tmp[5-i] = src[i];
		if (src == dst) System.arraycopy(tmp, 0, dst, 0,  6);
		return dst;
	}
	 
	 /**
	  * reorder the pluecker line coordinates to reflect the coordinates corresponding to
	  * a given permutation of the coordinates, specified by the array <i>perm</i>.
	  * @param dst
	  * @param src
	  * @param perm
	  * @return
	  */
	 public static double[] permuteCoordinates(double[] dst, double[] src, int[] perm)	{
		 double[] P = Rn.permutationMatrix(null, perm);
		 double[] M = lineToSkewMatrix(null, src);
		 double[] MM = Rn.conjugateByMatrix(null, M, P);
		 if (dst == null) dst = new double[src.length];
		 dst[0] = MM[11];
		 dst[1] = -MM[7];
		 dst[2] = MM[6];
		 dst[3] = MM[3];
		 dst[4] = MM[2];
		 dst[5] = MM[1];
		 return dst;
	 }

	public static double innerProduct(double[] l0, double[] l1) {
		double sum = 0;
		for (int i = 0; i<6; ++i)	{
			sum += l0[i] * l1[5-i];
		}
		return sum;
	}
